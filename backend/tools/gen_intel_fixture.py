"""Regenerate frontend/dev/intel-fixture.js (DEVELOPMENT FIXTURE, not a real run).

Runs the intelligence pipeline against a LOCAL copy of the demo shop: /shop, then
/shop?v=anomaly, with the human-written reference parser from the tests, a plain local
fetch instead of the sandbox, and no AI (rule-based assessments).

    cd backend && .venv/bin/python tools/gen_intel_fixture.py
"""
import json
import os
import socket
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
os.environ["INTEL_DATA_DIR"] = tempfile.mkdtemp(prefix="intel-fixture-")
sys.path[:0] = [str(BACKEND), str(BACKEND / "tests")]
from test_intelligence import fetch_stub, parse_table  # noqa: E402
from intelligence import pipeline  # noqa: E402

HEADER = """/**
 * ============================================================
 *  DEVELOPMENT FIXTURE — NOT A REAL RUN
 * ============================================================
 * Generated by backend/tools/gen_intel_fixture.py: the intelligence pipeline run
 * against a LOCAL copy of the demo shop (/shop, then /shop?v=anomaly) with a reference
 * parser, a plain local fetch instead of the sandbox and NO AI (rule-based
 * assessments). Used only with ?mock=anomaly.
 */
export const ANOMALY_FIXTURE = """


def main():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    env = dict(os.environ, SHOP_HOST="127.0.0.1", SHOP_PORT=str(port))
    shop = subprocess.Popen([sys.executable, str(BACKEND.parent / "demo-site" / "server.py")], env=env,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    base = f"http://127.0.0.1:{port}"
    try:
        for _ in range(50):
            try:
                urllib.request.urlopen(base + "/shop", timeout=1)
                break
            except OSError:
                time.sleep(0.1)

        def run(path, job_id, source):
            html = urllib.request.urlopen(base + path).read().decode()
            items = parse_table(html)
            intel = pipeline.analyze(job={"attempts": [{}]}, job_id=job_id, url=base + path, html=html,
                                     items=items, code='URL = "x"', source=source, verdict="pass",
                                     fetch=fetch_stub, chat=None, model=None)
            return items, intel

        run("/shop", "mockjob1", "generated")
        items, intel = run("/shop?v=anomaly", "mockjob2", "saved")
        text = json.dumps({"results": items, "intelligence": intel}, ensure_ascii=False, indent=1)
        text = text.replace(base, "http://70.34.217.56:8080")
        out = BACKEND.parent / "frontend" / "dev" / "intel-fixture.js"
        out.write_text(HEADER + text + ";\n", encoding="utf-8")
        print(f"wrote {out} ({len(intel['findings'])} findings)")
    finally:
        shop.terminate()


if __name__ == "__main__":
    main()
